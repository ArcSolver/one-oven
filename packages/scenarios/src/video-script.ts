import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Scenario } from './schema.js';
import type { ScenarioResult, TurnRecord } from './runner.js';

export const MAX_SECONDS = 170;
const WORDS_PER_SECOND = 2.5;
export type ScriptRow = { start: number; seconds: number; scene: string; shot: string; speaker: 'Narrator' | 'User' | 'Alexa' | 'Timer' | 'Title';
  line: string; screen: string; caption: string };
export type SourceRun = { scenario: Scenario; result: ScenarioResult; path?: string };

const words = (text: string) => text.trim().split(/\s+/).filter(Boolean).length;
const speak = (text: string, pad: number) => Math.round((words(text) / WORDS_PER_SECOND + pad) * 2) / 2;
export const timecode = (seconds: number) => `${Math.floor(seconds / 60)}:${String(Math.floor(seconds % 60)).padStart(2, '0')}`;
const screenFor = (ui: string | undefined, device: string) => ui === 'dot' || device === 'dot' ? 'Speaker only, light ring (no screen)'
  : ui === 'fullscreen' ? 'Full-screen Run of Show timeline' : 'Inline Now card';

/** Builds the shot list from passing runs. Assistant lines are the replies actually produced. */
export function buildScript(sources: SourceRun[], closing: string): ScriptRow[] {
  const rows: ScriptRow[] = [];
  let at = 0;
  const push = (row: Omit<ScriptRow, 'start'>) => { rows.push({ ...row, start: at }); at += row.seconds; };
  push({ seconds: 4, scene: 'Opening', shot: 'Title card over a home kitchen at 5 PM.', speaker: 'Title', line: 'One Oven: every dish on the table at the same time.',
    screen: 'Title card', caption: 'Simulated Alexa+ experience' });
  for (const { scenario, result } of [...sources].sort((a, b) => a.scenario.video.order - b.scenario.video.order)) {
    if (!result.passed) throw new Error(`${scenario.id}: video lines must come from a passing run`);
    const scene = scenario.video.scene;
    if (scenario.video.intro) push({ seconds: speak(scenario.video.intro, 0.5), scene, shot: `Scene ${scenario.video.order}: ${scenario.title}`,
      speaker: 'Narrator', line: scenario.video.intro, screen: screenFor(undefined, scenario.device), caption: '' });
    for (const beat of scenario.beats.filter(b => b.video)) {
      const video = beat.video!;
      const turns = result.turns.filter(t => t.beat === beat.id);
      const turn: TurnRecord | undefined = turns.at(-1);
      if (!turn) throw new Error(`${scenario.id}/${beat.id}: no recorded turn`);
      const screen = screenFor(video.ui, scenario.device);
      if (beat.repeat) push({ seconds: 6, scene, shot: video.shot, speaker: 'Narrator', line: '', screen, caption: video.caption ?? '' });
      const timer = video.timer ? turns.flatMap(t => t.timers)[0] : undefined;
      if (timer) push({ seconds: speak(timer.text, 1.5), scene, shot: 'Chime from the simulated host timer.', speaker: 'Timer', line: timer.text, screen, caption: '' });
      if (video.narration) push({ seconds: speak(video.narration, 0.5), scene, shot: video.shot, speaker: 'Narrator', line: video.narration, screen, caption: '' });
      push({ seconds: speak(turn.utterance, 0.5), scene, shot: beat.repeat ? 'Final step of the time-lapse.' : video.shot, speaker: 'User',
        line: turn.utterance, screen, caption: beat.repeat ? '' : video.caption ?? '' });
      push({ seconds: speak(turn.reply, 1), scene, shot: '', speaker: 'Alexa', line: turn.reply, screen, caption: '' });
    }
  }
  push({ seconds: speak(closing, 1), scene: 'Closing', shot: 'Developer panel: MCP tools/call log and measured numbers.', speaker: 'Narrator', line: closing,
    screen: 'Measured results card', caption: 'Timing guidance only. Check doneness with a food thermometer.' });
  const total = at;
  if (total > MAX_SECONDS) throw new Error(`Video script runs ${timecode(total)}, over ${timecode(MAX_SECONDS)}`);
  return rows;
}
export function scriptMarkdown(rows: ScriptRow[], sources: SourceRun[], root: string): string {
  const total = rows.reduce((n, r) => n + r.seconds, 0);
  const cell = (s: string) => s.replaceAll('|', '\\|');
  const lines = ['# One Oven demo video script (draft)', '',
    `Estimated length **${timecode(total)}** (cap ${timecode(MAX_SECONDS)}, rules allow under 3:00). English only. Generated by \`npm run video:script\`; do not edit lines by hand.`,
    'Spoken lines are the scenario utterances and the assistant replies recorded in these passing runs:', '',
    ...sources.map(s => `- ${s.scenario.id}: ${s.result.mode}${s.result.live ? ' live' : ''}, ${s.result.driver}${s.path ? ` — \`${relative(root, s.path)}\`` : ''}`), '',
    'Timing assumes 150 spoken words per minute plus a short pause per line; time-lapse rows are fixed 6 s b-roll.',
    'Production rules: no third-party music or logos, no real device photos; label the host as a simulated Alexa+ experience.', '',
    '| Time | Scene | Shot | Speaker | Line | Screen | Caption |', '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map(r => `| ${timecode(r.start)} | ${cell(r.scene)} | ${cell(r.shot)} | ${r.speaker} | ${cell(r.line)} | ${cell(r.screen)} | ${cell(r.caption)} |`), ''];
  return lines.join('\n');
}
export function scriptSrt(rows: ScriptRow[]): string {
  const stamp = (s: number) => `00:${String(Math.floor(s / 60)).padStart(2, '0')}:${String(Math.floor(s % 60)).padStart(2, '0')},${String(Math.round((s % 1) * 1000)).padStart(3, '0')}`;
  return rows.filter(r => r.line || r.caption).map((r, i) => `${i + 1}\n${stamp(r.start)} --> ${stamp(r.start + r.seconds)}\n${
    r.speaker === 'User' || r.speaker === 'Alexa' ? `${r.speaker}: ${r.line}` : r.line || r.caption}\n`).join('\n');
}
const PRIORITY = ['agent-live', 'voice-live', 'voice', 'agent', 'mcp', 'engine'];
/** Latest passing run for a scenario, preferring live model runs. */
export function findSource(runsRoot: string, scenario: Scenario): SourceRun | undefined {
  const directory = join(runsRoot, scenario.id);
  if (!existsSync(directory)) return undefined;
  const candidates = readdirSync(directory).map(name => join(directory, name, 'report.json')).filter(existsSync).map(path => {
    const result = JSON.parse(readFileSync(path, 'utf8')) as ScenarioResult;
    return { path: join(path, '..'), result, rank: PRIORITY.indexOf(`${result.mode}${result.live ? '-live' : ''}`), mtime: statSync(path).mtimeMs };
  }).filter(c => c.result.passed).sort((a, b) => a.rank - b.rank || b.mtime - a.mtime);
  const best = candidates[0];
  return best && { scenario, result: best.result, path: best.path };
}
